#!/usr/bin/env python3
"""Compute per-region sun-time analytics for the NZ DST dashboard.

Scenarios:
  keep      — status quo: NZST (UTC+12) winter, NZDT (UTC+13) summer
  abolish   — permanent NZST (UTC+12) all year
  permanent — permanent NZDT (UTC+13) all year

Metrics per region (computed from NOAA solar calculator, representative city):
  winter_sunrise  — sunrise time on the winter solstice (~21 June)
  winter_sunset   — sunset time on the winter solstice
  summer_solstice_sunset — sunset on ~21 Dec
  days_sunrise_after_7   — days/year where sunrise is at or after 07:00
  days_sunset_before_6   — days/year where sunset is before 18:00

All numbers generated by this script; nothing from memory. Representative cities
are the region's largest city (census-based, standard practice for regional sun profiles).
"""
import math, json, datetime

# ---------- NOAA solar calculator (translated to pure python) ----------
def sun_times(date, lat, lon, tz_offset_hours):
    """NOAA spreadsheet algorithm. Returns (sunrise, sunset, solar_noon) as local clock hours."""
    y, m, dd = date.year, date.month, date.day
    if m <= 2:
        y -= 1; m += 12
    A = y // 100
    B = 2 - A + A // 4
    jd = math.floor(365.25 * (y + 4716)) + math.floor(30.6001 * (m + 1)) + dd + B - 1524.5
    doy = date.timetuple().tm_yday
    frac_year = (2 * math.pi / 365.0) * (doy - 1 + (12 - 0.5) / 24.0)
    eqtime = 229.18 * (0.000075 + 0.001868 * math.cos(frac_year) - 0.032077 * math.sin(frac_year)
                       - 0.014615 * math.cos(2 * frac_year) - 0.040849 * math.sin(2 * frac_year))
    decl = (0.006918 - 0.399912 * math.cos(frac_year) + 0.070257 * math.sin(frac_year)
            - 0.006758 * math.cos(2 * frac_year) + 0.000907 * math.sin(2 * frac_year)
            - 0.002697 * math.cos(3 * frac_year) + 0.00148 * math.sin(3 * frac_year))
    cos_ha = (math.cos(math.radians(90.833)) / (math.cos(math.radians(lat)) * math.cos(decl))
              - math.tan(math.radians(lat)) * math.tan(decl))
    if cos_ha < -1 or cos_ha > 1:
        return None, None, None  # polar day/night — not for NZ
    ha = math.degrees(math.acos(cos_ha))
    sunrise_off = eqtime / 60.0 + (4.0 * lon) / 60.0 - tz_offset_hours
    sunrise = 12 - sunrise_off - ha / 15.0
    sunset = 12 - sunrise_off + ha / 15.0
    noon = 12 - sunrise_off
    return sunrise, sunset, noon

def fmt_h(h):
    if h is None:
        return None
    h = (h + 24) % 24
    hh = int(h); mm = int(round((h - hh) * 60))
    if mm == 60: hh += 1; mm = 0
    if hh == 24: hh = 0
    return f"{hh:02d}:{mm:02d}"

# ---------- NZ DST calendar (per Time Act 1974 / current govt.nz schedule) ----------
def is_nzdt(date):
    """NZDT = last Sunday of September 02:00 to first Sunday of April 03:00."""
    y = date.year
    # last Sunday of September
    d = datetime.date(y, 9, 30)
    while d.weekday() != 6:  # Sunday=6
        d -= datetime.timedelta(days=1)
    start = d
    # first Sunday of April
    d = datetime.date(y, 4, 1)
    while d.weekday() != 6:
        d += datetime.timedelta(days=1)
    end = d
    if date >= start:  # late Sept onward: NZDT until next April
        return True
    if date < end:     # Jan 1 to first Sunday of April: still NZDT from previous year's start
        return True
    return False

