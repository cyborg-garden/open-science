# Chatham Islands note (not a region; UTC+12:45/+13:45)
CHATHAMS = {
    "name": "Chatham Islands",
    "note": "Territory, not a region — runs 45 minutes ahead: UTC+12:45 standard, UTC+13:45 daylight.",
    "lat": -43.9, "lon": -176.5,
}

def scenario_offset(date, scenario):
    if scenario == "abolish":
        return 12
    if scenario == "permanent":
        return 13
    return 13 if is_nzdt(date) else 12  # keep

def compute_region(city, lat, lon, pop):
    out = {"city": city, "lat": lat, "lon": lon, "pop": pop, "scenarios": {}}
    for sc in ("keep", "abolish", "permanent"):
        ws = datetime.date(2026, 6, 21)
        ss = datetime.date(2026, 12, 22)
        r_w, s_w, _ = sun_times(ws, lat, lon, scenario_offset(ws, sc))
        r_s, s_s, _ = sun_times(ss, lat, lon, scenario_offset(ss, sc))
        # count days in a full year
        days_s_after_7 = days_s_before_6 = 0
        d = datetime.date(2026, 1, 1)
        end = datetime.date(2026, 12, 31)
        while d <= end:
            tz = scenario_offset(d, sc)
            r, s, _ = sun_times(d, lat, lon, tz)
            if r is not None:
                if r >= 7.0: days_s_after_7 += 1
                if s < 18.0: days_s_before_6 += 1
            d += datetime.timedelta(days=1)
        out["scenarios"][sc] = {
            "winter_sunrise": fmt_h(r_w),
            "winter_sunset": fmt_h(s_w),
            "summer_sunset": fmt_h(s_s),
            "days_sunrise_after_7": days_s_after_7,
            "days_sunset_before_6": days_s_before_6,
        }
    return out

def main():
    result = {"meta": {
        "computed": "2026-09-16",
        "method": "NOAA solar calculator, per-day loop over 2026, NZ DST calendar per Time Act 1974",
        "note_chathams": CHATHAMS["note"],
    }, "regions": {}}
    total_pop = sum(r[4] for r in REGIONS)
    national = {}
    for name, city, lat, lon, pop in REGIONS:
        result["regions"][name] = compute_region(city, lat, lon, pop)
    for sc in ("keep", "abolish", "permanent"):
        w_after7 = sum(result["regions"][r[0]]["scenarios"][sc]["days_sunrise_after_7"] * r[4] for r in REGIONS) / total_pop
        w_before6 = sum(result["regions"][r[0]]["scenarios"][sc]["days_sunset_before_6"] * r[4] for r in REGIONS) / total_pop
        national[sc] = {
            "pop_weighted_days_sunrise_after_7": round(w_after7, 1),
            "pop_weighted_days_sunset_before_6": round(w_before6, 1),
        }
    result["national"] = national
    result["meta"]["total_pop"] = total_pop
    print("national:", json.dumps(national, indent=1))
    with open('/opt/data/dst_dashboard/dst_data.json', 'w') as f:
        json.dump(result, f, indent=1)
    print("wrote dst_data.json")

if __name__ == "__main__":
    main()